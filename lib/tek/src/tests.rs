use super::*;

#[test]
fn test_decomp() {
    let compressed_data = include_bytes!("../../../src/initial-fs/GVIEW.HRB");
    let decompressed = tek_decomp(compressed_data).expect("Decompression failed");
    assert_eq!(decompressed.len(), 6056);
    assert_eq!(
        &decompressed[..32],
        &[
            0x00, 0x10, 0x46, 0x00, 0x48, 0x61, 0x72, 0x69, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x46, 0x00, 0x60, 0x00, 0x00, 0x00, 0x48, 0x17, 0x00, 0x00, 0x00, 0x00, 0x00, 0xe9,
            0x1c, 0x17, 0x00, 0x00,
        ]
    );
    assert_eq!(
        &decompressed[decompressed.len() - 32..],
        &[
            0x65, 0x63, 0x6f, 0x64, 0x65, 0x20, 0x65, 0x72, 0x72, 0x6f, 0x72, 0x2e, 0x0a, 0x00,
            0x00, 0x00, 0x03, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x02, 0x00, 0x00, 0x00,
        ]
    );
    assert_eq!(fnv1a64(&decompressed), 0xc7ca_c19a_1f83_a86e);
}

fn fnv1a64(bytes: &[u8]) -> u64 {
    let mut hash = 0xcbf2_9ce4_8422_2325u64;
    for &byte in bytes {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}
